package app

import "testing"

// Синонимы «завершить акт» обычным текстом — фикс бага из пилота
// (пользователь набрал «Завершить» без кнопки — бот не понял).
func TestIsFinishText(t *testing.T) {
	yes := []string{
		"Завершить", "завершить", "Завершить акт", "✅ Завершить акт",
		"завершить акт!", "Готово", "готово.", "Всё", "все", "Конец",
		"Хватит", "Закончил", "ок", "ОК", "OK", "done", "Finish", "больше нет",
	}
	no := []string{
		"штукатурка 45 260", "демонтаж 2000", "завершение работ 3000",
		"готовая смесь 250", "концеркрем 100", "", "зав", "гото",
	}
	for _, s := range yes {
		if !isFinishText(s) {
			t.Errorf("ожидал завершение: %q", s)
		}
	}
	for _, s := range no {
		if isFinishText(s) {
			t.Errorf("НЕ ожидал завершение: %q", s)
		}
	}
}

